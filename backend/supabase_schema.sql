-- Enable helpful PostgreSQL extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "unaccent";

-- ==============================================================================
-- 1. DROP EXISTING TABLES (Safe Re-run)
-- ==============================================================================
DROP TABLE IF EXISTS inquiries CASCADE;
DROP TABLE IF EXISTS properties CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ==============================================================================
-- 2. CREATE TABLES
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- Table: properties
-- Complete house & lot specifications, architectural dimensions, media & status
-- ------------------------------------------------------------------------------
CREATE TABLE properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    location TEXT NOT NULL,
    property_type TEXT NOT NULL,
    price NUMERIC(15, 2) NOT NULL,
    bedrooms INTEGER DEFAULT 3,
    bathrooms INTEGER DEFAULT 2,
    lot_area NUMERIC(10, 2) DEFAULT 120,
    floor_area NUMERIC(10, 2) DEFAULT 80,
    carports INTEGER DEFAULT 1,
    storeys INTEGER DEFAULT 2,
    status TEXT DEFAULT 'Available',
    image_url TEXT,
    description TEXT,
    amenities TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- ------------------------------------------------------------------------------
-- Table: inquiries
-- Client consultation requests and viewing schedule bookings
-- ------------------------------------------------------------------------------
CREATE TABLE inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_title TEXT,
    client_name TEXT NOT NULL,
    client_email TEXT NOT NULL,
    client_phone TEXT,
    message TEXT NOT NULL,
    status TEXT DEFAULT 'Under Review',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- ------------------------------------------------------------------------------
-- Table: users
-- Platform users, clients, and administrative accounts
-- ------------------------------------------------------------------------------
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    phone TEXT,
    role TEXT DEFAULT 'user',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- ==============================================================================
-- 3. PERFORMANCE INDEXES
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_properties_location ON properties(location);
CREATE INDEX IF NOT EXISTS idx_properties_type ON properties(property_type);
CREATE INDEX IF NOT EXISTS idx_properties_price ON properties(price);
CREATE INDEX IF NOT EXISTS idx_properties_status ON properties(status);
CREATE INDEX IF NOT EXISTS idx_inquiries_status ON inquiries(status);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);

-- ==============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================
ALTER TABLE properties ENABLE ROW LEVEL SECURITY;
ALTER TABLE inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;

-- Properties Policies: Public read access for visitors, full access for all operations
CREATE POLICY "Public can view properties"
    ON properties FOR SELECT
    USING (true);

CREATE POLICY "Allow insert properties"
    ON properties FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Allow update properties"
    ON properties FOR UPDATE
    USING (true);

CREATE POLICY "Allow delete properties"
    ON properties FOR DELETE
    USING (true);

-- Inquiries Policies: Anyone can submit an inquiry, anyone can read/manage
CREATE POLICY "Public can submit inquiries"
    ON inquiries FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Allow read inquiries"
    ON inquiries FOR SELECT
    USING (true);

CREATE POLICY "Allow update inquiries"
    ON inquiries FOR UPDATE
    USING (true);

CREATE POLICY "Allow delete inquiries"
    ON inquiries FOR DELETE
    USING (true);

-- Users Policies: Allow user authentication and account registration
CREATE POLICY "Allow read users"
    ON users FOR SELECT
    USING (true);

CREATE POLICY "Allow insert users"
    ON users FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Allow update users"
    ON users FOR UPDATE
    USING (true);

